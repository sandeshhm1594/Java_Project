
public class Datatypes {


	public static void main(String[] args) {
		
		byte age=127;
		short salary=32767;
		int ctc=5500000;
		long phone=9876543219l;
		
		float tax=18.345121f;
		double hike=30.5241567388d;
		
		char grade='A';
		
		boolean check=true;
		
		System.out.println("Age: "+age);
		System.out.println("Salary: "+salary);
		System.out.println("CTC "+ctc);
		System.out.println("Phone: "+phone);
		System.out.println("Tax: "+tax);
		System.out.println("Hike : "+hike);
		System.out.println("Grade: "+grade);
		System.out.println("Checking Condition: "+check);
		
		
		int num=0123;//octal calculation
		System.out.println(num);
		int num1=0x34;//HexaDecimal Calculation
		System.out.println(num1);
		
		
		
		
		
		
	}
}
